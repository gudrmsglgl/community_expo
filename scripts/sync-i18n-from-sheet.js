const fs = require("node:fs");
const path = require("node:path");

const DEFAULT_LANGUAGES = ["ko", "en"];
const REQUIRED_KEY_COLUMN = "key";

function getRequiredEnv(name) {
  const value = process.env[name];

  if (!value) {
    throw new Error(`Missing required environment variable: ${name}`);
  }

  return value;
}

function getCsvUrl() {
  if (process.env.I18N_SHEET_CSV_URL) {
    return process.env.I18N_SHEET_CSV_URL;
  }

  const sheetId = getRequiredEnv("I18N_GOOGLE_SHEET_ID");
  const gid = process.env.I18N_GOOGLE_SHEET_GID || "0";

  return `https://docs.google.com/spreadsheets/d/${sheetId}/export?format=csv&gid=${gid}`;
}

function getLanguages() {
  return (process.env.I18N_LANGUAGES ?? DEFAULT_LANGUAGES.join(","))
    .split(",")
    .map((language) => language.trim())
    .filter(Boolean);
}

function parseCsv(csv) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;

  for (let index = 0; index < csv.length; index += 1) {
    const character = csv[index];
    const nextCharacter = csv[index + 1];

    if (inQuotes) {
      if (character === '"' && nextCharacter === '"') {
        field += '"';
        index += 1;
      } else if (character === '"') {
        inQuotes = false;
      } else {
        field += character;
      }

      continue;
    }

    if (character === '"') {
      inQuotes = true;
    } else if (character === ",") {
      row.push(field);
      field = "";
    } else if (character === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (character !== "\r") {
      field += character;
    }
  }

  row.push(field);
  rows.push(row);

  return rows.filter((currentRow) =>
    currentRow.some((currentField) => currentField.trim() !== ""),
  );
}

function toRecords(rows) {
  const [headerRow, ...bodyRows] = rows;

  if (!headerRow) {
    throw new Error("The i18n sheet is empty.");
  }

  const headers = headerRow.map((header) => header.trim());
  const keyColumnIndex = headers.indexOf(REQUIRED_KEY_COLUMN);

  if (keyColumnIndex === -1) {
    throw new Error('The i18n sheet must include a "key" column.');
  }

  return bodyRows.map((row, rowIndex) => {
    const record = {};

    headers.forEach((header, columnIndex) => {
      record[header] = row[columnIndex]?.trim() ?? "";
    });

    if (!record.key) {
      throw new Error(`Missing key at sheet row ${rowIndex + 2}.`);
    }

    return record;
  });
}

function setNestedValue(target, dottedKey, value) {
  const parts = dottedKey.split(".").map((part) => part.trim());
  let current = target;

  if (parts.some((part) => part === "")) {
    throw new Error(`Invalid i18n key: "${dottedKey}"`);
  }

  parts.forEach((part, index) => {
    const isLeaf = index === parts.length - 1;

    if (isLeaf) {
      if (
        Object.prototype.hasOwnProperty.call(current, part) &&
        typeof current[part] === "object"
      ) {
        throw new Error(`Key conflict at "${dottedKey}".`);
      }

      current[part] = value;
      return;
    }

    if (!Object.prototype.hasOwnProperty.call(current, part)) {
      current[part] = {};
    }

    if (typeof current[part] !== "object" || current[part] === null) {
      throw new Error(`Key conflict at "${dottedKey}".`);
    }

    current = current[part];
  });
}

function buildLocale(records, language, allowEmpty) {
  const locale = {};
  const missingTranslations = [];

  records.forEach((record) => {
    const value = record[language];

    if (!allowEmpty && !value) {
      missingTranslations.push(record.key);
      return;
    }

    setNestedValue(locale, record.key, value ?? "");
  });

  if (missingTranslations.length > 0) {
    throw new Error(
      `Missing "${language}" translations for: ${missingTranslations.join(", ")}`,
    );
  }

  return locale;
}

function formatLocaleModule(locale) {
  return [
    "// This file is generated by scripts/sync-i18n-from-sheet.js.",
    "// Edit the Google Sheet instead of editing this file manually.",
    `const locale = ${JSON.stringify(locale, null, 2)};`,
    "",
    "export default locale;",
    "",
  ].join("\n");
}

async function fetchCsv() {
  const response = await fetch(getCsvUrl());

  if (!response.ok) {
    throw new Error(
      `Failed to fetch i18n sheet CSV: ${response.status} ${response.statusText}`,
    );
  }

  return response.text();
}

async function main() {
  const languages = getLanguages();
  const allowEmpty = process.env.I18N_ALLOW_EMPTY === "true";
  const csv = await fetchCsv();
  const records = toRecords(parseCsv(csv));
  const localeDirectory = path.resolve(
    process.env.I18N_OUTPUT_DIR ?? path.resolve(__dirname, "../i18n/locales"),
  );

  fs.mkdirSync(localeDirectory, { recursive: true });

  languages.forEach((language) => {
    const locale = buildLocale(records, language, allowEmpty);
    const outputPath = path.join(localeDirectory, `${language}.ts`);

    fs.writeFileSync(outputPath, formatLocaleModule(locale));
    console.log(`Updated ${path.relative(process.cwd(), outputPath)}`);
  });
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
